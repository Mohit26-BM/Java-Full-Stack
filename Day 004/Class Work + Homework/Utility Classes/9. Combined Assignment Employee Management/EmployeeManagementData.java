public class EmployeeManagementData {

    String id;
    String name;
    String department;
    double salary;
    int experience;

    EmployeeManagementData(String id, String name, String department,
                           double salary, int experience) {

        this.id = id;
        this.name = name;
        this.department = department;
        this.salary = salary;
        this.experience = experience;
    }
}